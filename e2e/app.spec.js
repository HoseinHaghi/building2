test('dashboard creates work for root and nested projects and starts a fresh draft',async({page})=>{
 test.setTimeout(180000);
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await register(page);
 const session=await (await page.request.get('/api/auth/me')).json();
 const headers={Origin:'http://127.0.0.1:5190','X-CSRF-Token':session.csrfToken};
 const project=async(name,parentId=null)=>{
  const response=await page.request.post('/api/projects',{headers,data:{name,parentId}});
  expect(response.status()).toBe(201);return response.json();
 };
 const root=await project('پروژه ریشه'),child=await project('بخش میانی',root.id),nested=await project('زیرمجموعه نهایی',child.id);
 const saveWork=async(title)=>{
  await page.getByLabel(/^عنوان کار/).fill(title);
  await page.getByLabel(/^شرح مختصر کار/).fill('توضیحات '+title);
  await page.getByLabel(/^شرح پیش نیاز/).fill('پیش نیاز آماده است');
  await page.getByRole('combobox',{name:/انتخاب طبقه/}).click();
  await page.getByRole('option',{name:'طبقه دوم',exact:true}).click();
  await page.getByRole('button',{name:'ایجاد',exact:true}).click();
  await expect(page.getByText(title,{exact:true})).toBeVisible();
  return (await page.request.get('/api'+new URL(page.url()).pathname)).json();
 };
 await page.goto('/dashboard?projectId='+root.id);
 await page.getByRole('button',{name:'ایجاد کار',exact:true}).click();
 await expect(page.getByRole('combobox',{name:/انتخاب پروژه/})).toContainText('پروژه ریشه');
 const rootWork=await saveWork('کار پروژه ریشه');
 expect(rootWork.projectId).toBe(root.id);
 await page.screenshot({path:'test-results/work-close-dashboard.png',animations:'disabled'});
 await page.getByRole('button',{name:'بازگشت به داشبورد',exact:true}).click();
 await expect(page).toHaveURL('http://127.0.0.1:5190/dashboard?projectId='+root.id);
 expect((await (await page.request.get('/api/works/'+encodeURIComponent(rootWork.id))).json()).status).toBe('in_progress');
 await page.getByRole('button',{name:'ایجاد کار',exact:true}).click();
 await page.getByLabel(/^عنوان کار/).fill('پیش نویس قبلی');
 await page.getByRole('button',{name:'انتخاب پروژه',exact:true}).click();
 await expect(page).toHaveURL(/\/select-project$/);
 await page.goto('/dashboard');
 await page.getByRole('button',{name:'پروژه‌ها',exact:true}).click();
 await page.getByText('پروژه ریشه',{exact:true}).click();
 await page.getByText('بخش میانی',{exact:true}).click();
 await page.getByText('زیرمجموعه نهایی',{exact:true}).click();
 await expect(page.getByRole('button',{name:'ایجاد کار',exact:true})).toHaveText('ایجاد کار');
 await page.screenshot({path:'test-results/dashboard-create-work-expanded.png',animations:'disabled'});
 await page.getByRole('button',{name:'ایجاد کار',exact:true}).click();
 await expect(page.getByRole('combobox',{name:/انتخاب پروژه/})).toContainText('زیرمجموعه نهایی');
 await expect(page.getByLabel(/^عنوان کار/)).toHaveValue('');
 await page.reload();
 await expect(page.getByRole('combobox',{name:/انتخاب پروژه/})).toContainText('زیرمجموعه نهایی');
 await page.getByRole('button',{name:'انصراف',exact:true}).click();
 await expect(page).toHaveURL('http://127.0.0.1:5190/dashboard?projectId='+nested.id);
 await page.getByRole('button',{name:'ایجاد کار',exact:true}).click();
 expect((await saveWork('کار زیرمجموعه نهایی')).projectId).toBe(nested.id);
 await page.reload();
 await expect(page.getByText('کار زیرمجموعه نهایی',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'بازگشت به داشبورد',exact:true}).click();
 await expect(page).toHaveURL('http://127.0.0.1:5190/dashboard?projectId='+nested.id);
 await expect(page.getByRole('button',{name:'کار زیرمجموعه نهایی',exact:true})).toBeVisible();
 expect(errors).toEqual([]);
});

